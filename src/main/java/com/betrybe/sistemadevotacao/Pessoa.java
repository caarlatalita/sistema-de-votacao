package com.betrybe.sistemadevotacao;

/**
 * The class Pessoa.
 */
public abstract class Pessoa {

  private String nome;

  /**
   * Gets nome.
   *
   * @return the nome
   */
  public String getNome() {
    return nome;
  }

  /**
   * Sets nome.
   *
   * @param nome the nome
   */
  public void setNome(String nome) {
    this.nome = nome;
  }
}
